  static I18n of(AppLang lang) {
    switch (lang) {
      case AppLang.zh:
        return I18n(lang, zh);
      case AppLang.en:
        return I18n(lang, en);
      case AppLang.ja:
        return I18n(lang, ja);
    }
  }

  /// 从平台语言检测默认语言。
  static AppLang fromPlatform() {
    // 这里默认中文界面环境；后续可接入系统 locale。
    return AppLang.zh;
  }
}

/// 全局当前语言（运行时可变）。应用启动时初始化。
AppLang currentLang = AppLang.zh;

/// 获取当前语言的字符串表。
I18n get i18n => I18n.of(currentLang);

/// 便捷翻译函数。
String tr(String key, {List<String> args = const []}) => i18n.tr(key, args: args);