  String tr(String key, {List<String> args = const []}) {
    var s = strings[key] ?? key;
    for (var i = 0; i < args.length; i++) {
      s = s.replaceAll('{$i}', args[i]);
    }
    // 兼容服务端直接下发的英文 / 中文原文：键若为空则原样返回
    return s;
